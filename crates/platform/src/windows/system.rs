fn shell_execute(target: &str, args: Option<&str>, dir: Option<&Path>) -> Result<(), String> {
    let file = wide(target);
    let params = args.map(wide);
    let directory = dir.map(|d| wide(&d.to_string_lossy()));
    let op = wide("open");
    unsafe {
        let h = windows_sys::Win32::UI::Shell::ShellExecuteW(
            std::ptr::null_mut(),
            op.as_ptr(),
            file.as_ptr(),
            params.as_ref().map(|p| p.as_ptr()).unwrap_or(std::ptr::null()),
            directory.as_ref().map(|d| d.as_ptr()).unwrap_or(std::ptr::null()),
            windows_sys::Win32::UI::WindowsAndMessaging::SW_SHOWNORMAL,
        );
        if (h as isize) <= 32 {
            return Err(format!("无法打开「{target}」（错误 {}）", h as isize));
        }
    }
    Ok(())
}

pub struct WinShell;

impl Shell for WinShell {
    fn launch(&self, target: &str) -> Result<(), String> {
        shell_execute(target, None, None)
    }

    fn open(&self, target: &str) -> Result<(), String> {
        shell_execute(target, None, None)
    }

    fn open_with(&self, app: &str, paths: &[PathBuf]) -> Result<(), String> {
        let args = paths.iter().map(|p| format!("\"{}\"", p.display())).collect::<Vec<_>>().join(" ");
        shell_execute(app, Some(&args), None)
    }

    fn open_terminal(&self, dir: &Path, terminal: Option<&str>) -> Result<(), String> {
        let term = terminal.unwrap_or("wt.exe");
        // Windows Terminal takes the start directory as `-d`; anything else is launched in the folder.
        if term.eq_ignore_ascii_case("wt.exe") || term.eq_ignore_ascii_case("wt") {
            return shell_execute("wt.exe", Some(&format!("-d \"{}\"", dir.display())), None);
        }
        shell_execute(term, None, Some(dir))
    }

    fn run_script(&self, r: &ScriptRun) -> Result<ScriptOutput, String> {
        let mut cmd = match (r.lang, r.is_file) {
            (ScriptLang::PowerShell, false) => {
                let mut c = std::process::Command::new("powershell.exe");
                c.args(["-NoProfile", "-NonInteractive", "-Command", r.source]);
                c
            }
            (ScriptLang::PowerShell, true) => {
                let mut c = std::process::Command::new("powershell.exe");
                c.args(["-NoProfile", "-NonInteractive", "-File", r.source]);
                c
            }
            (ScriptLang::Shell, false) => {
                let mut c = std::process::Command::new("cmd.exe");
                c.args(["/d", "/c", r.source]);
                c
            }
            (ScriptLang::Shell, true) => {
                let mut c = std::process::Command::new("cmd.exe");
                c.args(["/d", "/c", r.source]);
                c
            }
            (ScriptLang::AppleScript, _) => return Err("AppleScript 只在 macOS 上可用".into()),
        };
        cmd.envs(r.env.iter().map(|(k, v)| (k, v)));
        if let Some(cwd) = r.cwd {
            cmd.current_dir(cwd);
        }
        let out = run_hidden(&mut cmd, r.timeout)?;
        Ok(ScriptOutput { code: out.code, stdout: out.stdout, stderr: out.stderr })
    }

    fn confirm(&self, title: &str, message: &str) -> bool {
        let t = wide(title);
        let m = wide(message);
        unsafe { MessageBoxW(std::ptr::null_mut(), m.as_ptr(), t.as_ptr(), MB_YESNO | MB_ICONWARNING | MB_DEFBUTTON2 | MB_TOPMOST | MB_SETFOREGROUND) == IDYES }
    }

    fn notify(&self, title: &str, message: &str) {
        // A balloon needs a tray icon owned by a window with a message loop. A toast does not.
        let script = format!(
            "$t = {}; $m = {}; [Windows.UI.Notifications.ToastNotificationManager, Windows.UI.Notifications, ContentType = WindowsRuntime] | Out-Null; \
             $xml = [Windows.UI.Notifications.ToastNotificationManager]::GetTemplateContent([Windows.UI.Notifications.ToastTemplateType]::ToastText02); \
             $xml.GetElementsByTagName('text').Item(0).AppendChild($xml.CreateTextNode($t)) | Out-Null; \
             $xml.GetElementsByTagName('text').Item(1).AppendChild($xml.CreateTextNode($m)) | Out-Null; \
             $toast = [Windows.UI.Notifications.ToastNotification]::new($xml); \
             [Windows.UI.Notifications.ToastNotificationManager]::CreateToastNotifier('anyTools').Show($toast)",
            ps_quote(title),
            ps_quote(message)
        );
        std::thread::spawn(move || {
            let _ = powershell(&script, Duration::from_secs(10));
        });
    }
}


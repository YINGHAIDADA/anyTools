/// The clipboard sequence number right after anyTools restored a snapshot. Clipboard history skips
/// exactly that change.
static RESTORED_AT: AtomicI64 = AtomicI64::new(-1);
/// Set while the selection probe borrows the clipboard.
static BUSY: AtomicBool = AtomicBool::new(false);

pub(super) fn set_busy(on: bool) {
    BUSY.store(on, Ordering::Release);
}

/// A clipboard format other history tools recognise as "don't record this". Set on text anyTools only
/// puts on the clipboard so it can paste it a moment later.
const TRANSIENT_FORMAT: &str = "org.nspasteboard.TransientType";

/// Formats that mark the clipboard content as sensitive or transient. Password managers set these.
const SKIP_FORMATS: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "ExcludeClipboardContentFromMonitorProcessing",
    "CanIncludeInClipboardHistory",
];

const CF_UNICODETEXT: u32 = 13;
const CF_HDROP: u32 = 15;

/// Outcome of a child process.
pub struct Output {
    pub code: i32,
    pub stdout: String,
    pub stderr: String,
}

/// Runs `cmd` with no console window, collecting both streams, and kills it after `timeout`.
pub fn run_hidden(cmd: &mut std::process::Command, timeout: Duration) -> Result<Output, String> {
    use std::os::windows::process::CommandExt;
    // CREATE_NO_WINDOW: a console subsystem child would otherwise flash a console.
    cmd.creation_flags(0x0800_0000);
    cmd.stdin(std::process::Stdio::null()).stdout(std::process::Stdio::piped()).stderr(std::process::Stdio::piped());
    let mut child = cmd.spawn().map_err(|e| format!("无法启动进程: {e}"))?;
    let (mut so, mut se) = (child.stdout.take().unwrap(), child.stderr.take().unwrap());
    let out_t = std::thread::spawn(move || {
        let mut s = String::new();
        let _ = so.read_to_string(&mut s);
        s
    });
    let err_t = std::thread::spawn(move || {
        let mut s = String::new();
        let _ = se.read_to_string(&mut s);
        s
    });
    let start = Instant::now();
    let status = loop {
        if let Some(st) = child.try_wait().map_err(|e| e.to_string())? {
            break st;
        }
        if start.elapsed() > timeout {
            let _ = child.kill();
            let _ = child.wait();
            return Err(format!("运行超时（>{}秒），已终止", timeout.as_secs()));
        }
        std::thread::sleep(Duration::from_millis(10));
    };
    Ok(Output { code: status.code().unwrap_or(-1), stdout: out_t.join().unwrap_or_default(), stderr: err_t.join().unwrap_or_default() })
}

fn powershell(script: &str, timeout: Duration) -> Result<Output, String> {
    let mut cmd = std::process::Command::new("powershell.exe");
    cmd.args(["-NoProfile", "-NonInteractive", "-Command", script]);
    run_hidden(&mut cmd, timeout)
}

fn ps_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}


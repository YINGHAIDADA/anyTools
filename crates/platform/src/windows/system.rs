pub struct WinIcons;

fn icon_png(path: &str, size: u32) -> Option<Vec<u8>> {
    use windows_sys::Win32::Graphics::Gdi::{CreateCompatibleDC, CreateDIBSection, DeleteDC, DeleteObject, GetDC, ReleaseDC, SelectObject, BITMAPINFO, BITMAPINFOHEADER, DIB_RGB_COLORS};
    use windows_sys::Win32::UI::Shell::{SHGetFileInfoW, SHFILEINFOW, SHGFI_ICON, SHGFI_LARGEICON};
    use windows_sys::Win32::UI::WindowsAndMessaging::{DestroyIcon, DrawIconEx, DI_NORMAL};
    unsafe {
        let w = wide(path);
        let mut info = SHFILEINFOW::default();
        let got = SHGetFileInfoW(w.as_ptr(), 0, &mut info, std::mem::size_of::<SHFILEINFOW>() as u32, SHGFI_ICON | SHGFI_LARGEICON);
        if got == 0 || info.hIcon.is_null() {
            return None;
        }
        let screen = GetDC(std::ptr::null_mut());
        let dc = CreateCompatibleDC(screen);
        let bmi = BITMAPINFO {
            bmiHeader: BITMAPINFOHEADER {
                biSize: std::mem::size_of::<BITMAPINFOHEADER>() as u32,
                biWidth: size as i32,
                biHeight: -(size as i32),
                biPlanes: 1,
                biBitCount: 32,
                ..BITMAPINFOHEADER::default()
            },
            ..BITMAPINFO::default()
        };
        let mut bits: *mut u8 = std::ptr::null_mut();
        let bmp = CreateDIBSection(dc, &bmi, DIB_RGB_COLORS, &mut bits as *mut *mut u8 as *mut *mut _, std::ptr::null_mut(), 0);
        let png = if !bmp.is_null() && !bits.is_null() {
            let old = SelectObject(dc, bmp as _);
            DrawIconEx(dc, 0, 0, info.hIcon, size as i32, size as i32, 0, std::ptr::null_mut(), DI_NORMAL);
            SelectObject(dc, old);
            let pixels = std::slice::from_raw_parts(bits, (size * size * 4) as usize);
            let mut rgba = Vec::with_capacity(pixels.len());
            // GDI writes premultiplied BGRA; the PNG wants straight RGBA.
            for px in pixels.chunks_exact(4) {
                let a = px[3] as u32;
                let (r, g, b) = if a == 0 { (0, 0, 0) } else { ((px[2] as u32 * 255 / a) as u8, (px[1] as u32 * 255 / a) as u8, (px[0] as u32 * 255 / a) as u8) };
                rgba.extend_from_slice(&[r, g, b, a as u8]);
            }
            encode_png(size, &rgba)
        } else {
            None
        };
        if !bmp.is_null() {
            DeleteObject(bmp as _);
        }
        DeleteDC(dc);
        ReleaseDC(std::ptr::null_mut(), screen);
        DestroyIcon(info.hIcon);
        png
    }
}

fn encode_png(size: u32, rgba: &[u8]) -> Option<Vec<u8>> {
    let img = image::RgbaImage::from_raw(size, size, rgba.to_vec())?;
    let mut buf = std::io::Cursor::new(Vec::new());
    img.write_with_encoder(image::codecs::png::PngEncoder::new(&mut buf)).ok()?;
    Some(buf.into_inner())
}

impl Icons for WinIcons {
    fn app_icon_png(&self, target: &str, size: u32) -> Option<Vec<u8>> {
        icon_png(target, size).or_else(|| {
            // Not a path: ask `where` to resolve the command, then take that file's icon.
            let mut cmd = std::process::Command::new("where.exe");
            cmd.arg(target);
            let out = run_hidden(&mut cmd, Duration::from_secs(3)).ok()?;
            let first = out.stdout.lines().next()?.trim();
            (!first.is_empty()).then(|| icon_png(first, size)).flatten()
        })
    }
}

/// The desktop folder, for callers that want a default directory.
#[allow(dead_code)]
pub fn desktop_dir() -> Option<PathBuf> {
    known_folder(windows_sys::Win32::UI::Shell::FOLDERID_Desktop)
}

fn known_folder(id: windows_sys::core::GUID) -> Option<PathBuf> {
    unsafe {
        let mut p: windows_sys::core::PWSTR = std::ptr::null_mut();
        if SHGetKnownFolderPath(&id, 0, std::ptr::null_mut(), &mut p) != 0 || p.is_null() {
            return None;
        }
        let mut len = 0;
        while *p.add(len) != 0 {
            len += 1;
        }
        let s = from_wide(std::slice::from_raw_parts(p, len));
        windows_sys::Win32::System::Com::CoTaskMemFree(p as *const _);
        Some(PathBuf::from(s))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quotes_powershell_strings() {
        assert_eq!(ps_quote("a'b"), "'a''b'");
        assert_eq!(ps_quote("plain"), "'plain'");
    }

    #[test]
    fn hdrop_round_trip_bytes() {
        // The header must point past itself and flag wide characters, or Explorer reads garbage.
        let paths = vec![PathBuf::from("C:\\a.txt"), PathBuf::from("D:\\b")];
        let mut list: Vec<u16> = Vec::new();
        for p in &paths {
            list.extend(p.to_string_lossy().encode_utf16());
            list.push(0);
        }
        list.push(0);
        assert!(list.ends_with(&[0, 0]));
        assert_eq!(list.iter().filter(|c| **c == 0).count(), 3);
    }
}

pub struct WinFiles;

impl FileOps for WinFiles {
    fn trash(&self, paths: &[PathBuf]) -> Result<(), String> {
        for p in paths {
            let which = if p.is_dir() { "DeleteDirectory" } else { "DeleteFile" };
            let script = format!(
                "Add-Type -AssemblyName Microsoft.VisualBasic; [Microsoft.VisualBasic.FileIO.FileSystem]::{which}({}, 'OnlyErrorDialogs', 'SendToRecycleBin')",
                ps_quote(&p.to_string_lossy())
            );
            let out = powershell(&script, Duration::from_secs(30))?;
            if out.code != 0 {
                return Err(format!("移到回收站失败: {}", out.stderr.trim()));
            }
        }
        Ok(())
    }

    fn set_clipboard_files(&self, paths: &[PathBuf]) -> Result<(), String> {
        with_clipboard(|| {
            unsafe {
                if EmptyClipboard() == 0 {
                    return Err(last_error("清空剪贴板失败"));
                }
            }
            write_hdrop(paths)
        })
    }

    fn clipboard_files(&self) -> Vec<PathBuf> {
        with_clipboard(|| Ok(read_hdrop())).unwrap_or_default()
    }

    fn set_clipboard_text(&self, text: &str) -> Result<(), String> {
        with_clipboard(|| {
            unsafe {
                if EmptyClipboard() == 0 {
                    return Err(last_error("清空剪贴板失败"));
                }
            }
            write_text(text)
        })
    }

    fn clipboard_text(&self) -> Option<String> {
        with_clipboard(|| Ok(read_text())).ok().flatten()
    }

    fn zip(&self, base: &Path, paths: &[PathBuf], dest: &Path) -> Result<(), String> {
        let items = paths.iter().map(|p| ps_quote(&p.strip_prefix(base).unwrap_or(p).to_string_lossy())).collect::<Vec<_>>().join(", ");
        let script = format!("Compress-Archive -Path {items} -DestinationPath {} -Force", ps_quote(&dest.to_string_lossy()));
        let mut cmd = std::process::Command::new("powershell.exe");
        cmd.args(["-NoProfile", "-NonInteractive", "-Command", &script]).current_dir(base);
        let out = run_hidden(&mut cmd, Duration::from_secs(120))?;
        if out.code == 0 {
            Ok(())
        } else {
            Err(format!("压缩失败: {}", out.stderr.trim()))
        }
    }

    fn clipboard_change_count(&self) -> i64 {
        unsafe { GetClipboardSequenceNumber() as i64 }
    }

    fn clipboard_text_for_history(&self) -> Option<String> {
        with_clipboard(|| {
            let names = clipboard_format_names();
            if names.iter().any(|n| SKIP_FORMATS.iter().any(|s| n.eq_ignore_ascii_case(s))) {
                return Ok(None);
            }
            Ok(read_text())
        })
        .ok()
        .flatten()
    }

    fn clipboard_snapshot(&self) -> ClipboardSnapshot {
        snapshot()
    }

    fn clipboard_restore(&self, snap: &ClipboardSnapshot) -> Result<(), String> {
        restore(snap)
    }

    fn clipboard_restored_at(&self) -> i64 {
        RESTORED_AT.load(Ordering::Acquire)
    }

    fn clipboard_busy(&self) -> bool {
        BUSY.load(Ordering::Acquire)
    }

    fn set_clipboard_text_transient(&self, text: &str) -> Result<(), String> {
        with_clipboard(|| {
            unsafe {
                if EmptyClipboard() == 0 {
                    return Err(last_error("清空剪贴板失败"));
                }
            }
            write_text(text)?;
            mark_transient();
            Ok(())
        })
    }
}


/// Opens the clipboard, retrying briefly: another app often holds it for a few milliseconds.
fn with_clipboard<T>(f: impl FnOnce() -> Result<T, String>) -> Result<T, String> {
    let start = Instant::now();
    loop {
        if unsafe { OpenClipboard(std::ptr::null_mut()) } != 0 {
            let res = f();
            unsafe { CloseClipboard() };
            return res;
        }
        if start.elapsed() > Duration::from_millis(300) {
            return Err(last_error("无法打开剪贴板"));
        }
        std::thread::sleep(Duration::from_millis(5));
    }
}

fn read_text() -> Option<String> {
    unsafe {
        let h = GetClipboardData(CF_UNICODETEXT);
        if h.is_null() {
            return None;
        }
        let p = GlobalLock(h as _) as *const u16;
        if p.is_null() {
            return None;
        }
        let n = (GlobalSize(h as _) / 2).saturating_sub(1);
        let s = from_wide(std::slice::from_raw_parts(p, n));
        GlobalUnlock(h as _);
        Some(s)
    }
}

fn write_global(bytes: &[u8]) -> Result<HANDLE, String> {
    unsafe {
        let h = GlobalAlloc(GMEM_MOVEABLE, bytes.len().max(1));
        if h.is_null() {
            return Err("内存不足".into());
        }
        let p = GlobalLock(h) as *mut u8;
        if p.is_null() {
            return Err("内存不足".into());
        }
        if !bytes.is_empty() {
            std::ptr::copy_nonoverlapping(bytes.as_ptr(), p, bytes.len());
        }
        GlobalUnlock(h);
        Ok(h as HANDLE)
    }
}

fn write_text(text: &str) -> Result<(), String> {
    let units: Vec<u16> = text.encode_utf16().chain(std::iter::once(0)).collect();
    let bytes = unsafe { std::slice::from_raw_parts(units.as_ptr() as *const u8, units.len() * 2) };
    let h = write_global(bytes)?;
    unsafe {
        if SetClipboardData(CF_UNICODETEXT, h).is_null() {
            return Err(last_error("写入剪贴板失败"));
        }
    }
    Ok(())
}

fn write_hdrop(paths: &[PathBuf]) -> Result<(), String> {
    // DROPFILES header (20 bytes: pFiles, pt, fNC, fWide), then the double-NUL-terminated UTF-16 list.
    let mut list: Vec<u16> = Vec::new();
    for p in paths {
        list.extend(p.to_string_lossy().encode_utf16());
        list.push(0);
    }
    list.push(0);
    let header = 20usize;
    let mut bytes = vec![0u8; header + list.len() * 2];
    bytes[..4].copy_from_slice(&(header as u32).to_ne_bytes());
    bytes[16..20].copy_from_slice(&1i32.to_ne_bytes()); // fWide
    let list_bytes = unsafe { std::slice::from_raw_parts(list.as_ptr() as *const u8, list.len() * 2) };
    bytes[header..].copy_from_slice(list_bytes);
    let h = write_global(&bytes)?;
    unsafe {
        if SetClipboardData(CF_HDROP, h).is_null() {
            return Err(last_error("写入剪贴板失败"));
        }
    }
    Ok(())
}

fn read_hdrop() -> Vec<PathBuf> {
    unsafe {
        let h = GetClipboardData(CF_HDROP);
        if h.is_null() {
            return vec![];
        }
        hdrop_paths(h as windows_sys::Win32::UI::Shell::HDROP)
    }
}

fn hdrop_paths(hdrop: windows_sys::Win32::UI::Shell::HDROP) -> Vec<PathBuf> {
    unsafe {
        let n = windows_sys::Win32::UI::Shell::DragQueryFileW(hdrop, 0xFFFF_FFFF, std::ptr::null_mut(), 0);
        let mut out = Vec::with_capacity(n as usize);
        for i in 0..n {
            let len = windows_sys::Win32::UI::Shell::DragQueryFileW(hdrop, i, std::ptr::null_mut(), 0);
            let mut buf = vec![0u16; len as usize + 1];
            windows_sys::Win32::UI::Shell::DragQueryFileW(hdrop, i, buf.as_mut_ptr(), buf.len() as u32);
            let s = from_wide(&buf);
            if !s.is_empty() {
                out.push(PathBuf::from(s));
            }
        }
        out
    }
}

fn format_name(format: u32) -> Option<String> {
    unsafe {
        let mut buf = [0u16; 256];
        let n = GetClipboardFormatNameW(format, buf.as_mut_ptr(), buf.len() as i32);
        (n > 0).then(|| from_wide(&buf[..n as usize]))
    }
}

fn clipboard_format_names() -> Vec<String> {
    let mut out = vec![];
    unsafe {
        let mut fmt = 0u32;
        loop {
            fmt = EnumClipboardFormats(fmt);
            if fmt == 0 {
                break;
            }
            if let Some(name) = format_name(fmt) {
                out.push(name);
            }
        }
    }
    out
}

fn register_format(name: &str) -> u32 {
    let w = wide(name);
    unsafe { RegisterClipboardFormatW(w.as_ptr()) }
}

fn mark_transient() {
    let fmt = register_format(TRANSIENT_FORMAT);
    if fmt == 0 {
        return;
    }
    if let Ok(h) = write_global(&[0]) {
        unsafe { SetClipboardData(fmt, h) };
    }
}

/// Everything currently on the clipboard, so it can be put back byte for byte.
fn snapshot() -> ClipboardSnapshot {
    with_clipboard(|| {
        let mut items = vec![];
        unsafe {
            let mut fmt = 0u32;
            loop {
                fmt = EnumClipboardFormats(fmt);
                if fmt == 0 {
                    break;
                }
                let h = GetClipboardData(fmt);
                if h.is_null() {
                    continue;
                }
                let p = GlobalLock(h as _) as *const u8;
                if p.is_null() {
                    continue;
                }
                let n = GlobalSize(h as _);
                let bytes = std::slice::from_raw_parts(p, n).to_vec();
                GlobalUnlock(h as _);
                let name = format_name(fmt).unwrap_or_else(|| format!("#{fmt}"));
                items.push((name, bytes));
            }
        }
        Ok(vec![items])
    })
    .unwrap_or_default()
}

fn restore(snap: &ClipboardSnapshot) -> Result<(), String> {
    with_clipboard(|| {
        unsafe {
            if EmptyClipboard() == 0 {
                return Err(last_error("清空剪贴板失败"));
            }
        }
        for (name, bytes) in snap.first().into_iter().flatten() {
            let fmt = if let Some(n) = name.strip_prefix('#') { n.parse().unwrap_or(0) } else { register_format(name) };
            if fmt == 0 {
                continue;
            }
            if let Ok(h) = write_global(bytes) {
                unsafe { SetClipboardData(fmt, h) };
            }
        }
        Ok(())
    })?;
    RESTORED_AT.store(unsafe { GetClipboardSequenceNumber() } as i64, Ordering::Release);
    Ok(())
}

// -------------------------------------------------------------------------------------------------
// Selection via Ctrl+C (the clipboard is restored afterwards)
// -------------------------------------------------------------------------------------------------

pub fn copy_selection(timeout: Duration) -> Result<Option<String>, String> {
    use super::input::WinKeyboard;
    use anytools_core::keys::{Chord, Mods};
    set_busy(true);
    let res = (|| {
        let snap = snapshot();
        let before = unsafe { GetClipboardSequenceNumber() };
        WinKeyboard.send_chord(&Chord { mods: Mods::CTRL, key: "c".into() })?;
        let start = Instant::now();
        let mut text = None;
        while start.elapsed() < timeout {
            std::thread::sleep(Duration::from_millis(10));
            if unsafe { GetClipboardSequenceNumber() } != before {
                text = with_clipboard(|| Ok(read_text())).ok().flatten().filter(|s| !s.trim().is_empty());
                break;
            }
        }
        if unsafe { GetClipboardSequenceNumber() } != before {
            restore(&snap)?;
        }
        Ok(text)
    })();
    set_busy(false);
    res
}

